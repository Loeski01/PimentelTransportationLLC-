'use strict';
const assert = require('node:assert/strict');
const {diffBooking,buildModificationEvent,adminModificationMessage}=require('./modification');
const before={reference:'PT-TEST',name:'Sample Passenger',tripType:'round_trip',status:'confirmed',from:'Boston',to:'Cambridge',date:'2026-12-01',time:'10:00',returnDate:'2026-12-02',returnTime:'14:00',phone:'5550000000'};
const changed=diffBooking(before,{time:'11:00'});
assert.equal(changed.after.time,'11:00');
assert.equal(before.time,'10:00');
assert.deepEqual(changed.changes,[{field:'time',oldValue:'10:00',newValue:'11:00'}]);
assert.throws(()=>diffBooking(before,{time:'10:00'}),/No changes/);
assert.throws(()=>diffBooking(before,{status:'completed'}),/Unsupported/);
assert.throws(()=>diffBooking(before,{returnDate:'2026-11-30'}),/Return must be after/);
assert.throws(()=>diffBooking(before,{date:'2026-02-30'}),/Invalid date/);
assert.throws(()=>diffBooking({...before,status:'in_progress'},{time:'11:00'}),/not eligible/);
assert.throws(()=>diffBooking(before,{time:'25:00'}),/Invalid time/);
const event=buildModificationEvent({before,patch:{time:'11:00'},previousFareCents:20000,newFareCents:21000,now:new Date('2026-11-18T10:30:00Z')});
assert.equal(event.priceDifferenceCents,1000);
assert.equal(event.bookingReference,'PT-TEST');
assert.match(adminModificationMessage(event),/10:00 -> 11:00/);
assert.match(adminModificationMessage(event),/Sample Passenger/);
assert.throws(()=>buildModificationEvent({before,patch:{time:'11:00'},previousFareCents:-1,newFareCents:0}),/Invalid fare/);
console.log('Booking modification unit tests passed (12 assertions)');
